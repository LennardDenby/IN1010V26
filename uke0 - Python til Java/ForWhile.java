public class ForWhile {
    public static void main(String[] args) {
        for (int i = 0; i < 10; i ++) {
            System.out.println("Hei" + i);
        }

        int num = 0;
        while (num < 10) {
            System.out.println("Hei" + num);
            num++;
        }
    }
}